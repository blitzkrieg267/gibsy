<?php
/*
Kreck Bridge — Salary payment receipt.
Rendered printable via report.php (…/report.php?q=/modules/Kreck Bridge/kreck_salary_receipt.php&kreckSalaryPaymentID=ID),
and also viewable as a normal page. Reuses Gibbon's org settings for the header.
*/

require_once __DIR__ . '/src/SalaryManager.php';

use Gibbon\Contracts\Database\Connection;
use Gibbon\Domain\System\SettingGateway;
use Gibbon\Services\Format;

// Gated by the payroll-run action (this page is in its URLList).
if (isActionAccessible($guid, $connection2, '/modules/Kreck Bridge/kreck_salary_run.php') == false) {
    $page->addError(__('You do not have access to this action.'));
    return;
}

$id = $_GET['kreckSalaryPaymentID'] ?? '';
$manager = new KreckSalaryManager($container->get(Connection::class));
$pay = $id ? $manager->getPayment($id) : null;

if (!$pay) {
    $page->addError(__('Payment not found.'));
    return;
}

$settingGateway = $container->get(SettingGateway::class);
$orgName = $settingGateway->getSettingByScope('System', 'organisationName');
$orgNameShort = $settingGateway->getSettingByScope('System', 'organisationNameShort');
$currency = preg_replace('/\s*\[.*/', '', (string) $settingGateway->getSettingByScope('System', 'currency'));
$staffName = Format::name($pay['title'] ?? '', $pay['preferredName'], $pay['surname'], 'Staff', false);
$periodLabel = KreckSalaryManager::periodLabel($pay['period']);
$isPaid = ($pay['status'] === 'Paid');

ob_start();
?>
<div style="max-width:640px;margin:0 auto;font-family:Arial,Helvetica,sans-serif;color:#0f1e2e">
    <div style="border-bottom:3px solid #0e9f9a;padding-bottom:10px;margin-bottom:16px;display:flex;justify-content:space-between;align-items:flex-end">
        <div>
            <div style="font-size:22px;font-weight:800"><?php echo htmlspecialchars($orgName ?: 'School'); ?></div>
            <div style="color:#48596b"><?php echo __('Salary Payment Receipt'); ?></div>
        </div>
        <div style="text-align:right;color:#48596b;font-size:13px">
            <?php echo __('Receipt'); ?> #<?php echo htmlspecialchars(ltrim((string) $pay['kreckSalaryPaymentID'], '0')); ?><br>
            <?php echo htmlspecialchars(date('j M Y')); ?>
        </div>
    </div>

    <table style="width:100%;border-collapse:collapse;font-size:15px">
        <tr><td style="padding:7px 0;color:#48596b;width:40%"><?php echo __('Paid to'); ?></td><td style="padding:7px 0;font-weight:700"><?php echo htmlspecialchars($staffName); ?> (<?php echo htmlspecialchars($pay['username']); ?>)</td></tr>
        <tr><td style="padding:7px 0;color:#48596b"><?php echo __('Pay period'); ?></td><td style="padding:7px 0"><?php echo htmlspecialchars($periodLabel); ?></td></tr>
        <tr><td style="padding:7px 0;color:#48596b"><?php echo __('Amount'); ?></td><td style="padding:7px 0;font-weight:800;font-size:18px"><?php echo htmlspecialchars($currency); ?><?php echo number_format((float) $pay['amount'], 2); ?></td></tr>
        <tr><td style="padding:7px 0;color:#48596b"><?php echo __('Status'); ?></td><td style="padding:7px 0"><?php echo htmlspecialchars($pay['status']); ?></td></tr>
        <?php if ($isPaid): ?>
        <tr><td style="padding:7px 0;color:#48596b"><?php echo __('Payment date'); ?></td><td style="padding:7px 0"><?php echo htmlspecialchars((string) $pay['paymentDate']); ?></td></tr>
        <tr><td style="padding:7px 0;color:#48596b"><?php echo __('Method'); ?></td><td style="padding:7px 0"><?php echo htmlspecialchars((string) $pay['paymentMethod']); ?></td></tr>
        <tr><td style="padding:7px 0;color:#48596b"><?php echo __('Proof of payment'); ?></td><td style="padding:7px 0"><?php echo !empty($pay['proofOfPayment']) ? __('Attached on file') : __('—'); ?></td></tr>
        <?php endif; ?>
    </table>

    <p style="margin-top:22px;color:#8595a4;font-size:12px">
        <?php echo __('This receipt was generated by KRECK on behalf of'); ?> <?php echo htmlspecialchars($orgNameShort ?: $orgName); ?>.
        <?php echo __('It is a record of salary payment and does not constitute a tax document.'); ?>
    </p>
</div>
<?php
echo ob_get_clean();
